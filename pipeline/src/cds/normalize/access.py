def _gdc(rec: DatasetRecord) -> list[tuple[str, AccessStep]]:
    project = _first(_ids(rec, "gdc_project_id"))
    if not project:
        return []
    phs = _first(_ids(rec, "dbgap_phs"))
    phs_url = next((i.url for i in rec.identifiers if i.scheme == "dbgap_phs" and i.url), None)
    n_open = _component(rec.access.open_components)
    n_ctrl = _component(rec.access.controlled_components)
    label = "GDC access documentation"
    out: list[tuple[str, AccessStep]] = []

    out.append(
        (
            label,
            AccessStep(
                order=0,
                action="Open the project in the GDC Data Portal",
                detail=(
                    "The portal is the authority on how many cases and files this "
                    "project currently holds. Check those counts against the ones on "
                    "this page before requesting anything."
                ),
                url=rec.landing_page_url,
                est_time="5 minutes",
            ),
        )
    )
    if n_open:
        out.append(
            (
                label,
                AccessStep(
                    order=0,
                    action="Download the open files without an account",
                    detail=(
                        f"{n_open} are open access: no login, no request. Add them to "
                        "the portal cart to get a manifest, then fetch it with the GDC "
                        "Data Transfer Tool."
                    ),
                    url=GDC_TRANSFER_TOOL,
                    est_time="minutes to hours, by cohort size",
                    cli_snippet="gdc-client download -m gdc_manifest.txt",
                ),
            )
        )
    if n_ctrl:
        out.append(
            (
                label,
                AccessStep(
                    order=0,
                    action="Request controlled access through dbGaP",
                    detail=(
                        f"{n_ctrl} hold sequence-level data and are released only under "
                        "an approved data access request"
                        + (f" for {phs}." if phs else ".")
                        + " The request starts at dbGaP, not in the portal, and it is "
                        "your institution's signing official who submits it."
                    ),
                    url=GDC_CONTROLLED,
                    requires=(
                        ["eRA Commons account", "institutional signing official approval"]
                        + ([f"dbGaP data access request for {phs}"] if phs else [])
                    ),
                    est_time=rec.access.typical_turnaround or "days to a few weeks",
                ),
            )
        )
        out.append(
            (
                label,
                AccessStep(
                    order=0,
                    action="Download controlled files with your token",
                    detail=(
                        "An approved request yields a token that expires monthly. The "
                        "same manifest fetches nothing without it."
                    ),
                    url=phs_url or GDC_CONTROLLED,
                    requires=["approved dbGaP request", "GDC authentication token"],
                    cli_snippet=("gdc-client download -m gdc_manifest.txt -t gdc-user-token.txt"),
                ),
            )
        )
    out.append(
        (
            label,
            AccessStep(
                order=0,
                action="Query the project from code, with no credentials",
                detail=(
                    "The file index is public even where the files are not, so an agent "
                    "can size a cohort before anyone requests access."
                ),
                url=GDC_API,
                audience=AccessAudience.AGENT,
                cli_snippet=(
                    "curl -s 'https://api.gdc.cancer.gov/files' --get \\\n"
                    '  --data-urlencode \'filters={"op":"and","content":['
                    '{"op":"in","content":{"field":"cases.project.project_id",'
                    f'"value":["{project}"]}}}},'
                    '{"op":"in","content":{"field":"access","value":["open"]}}]}\' \\\n'
                    "  --data-urlencode 'fields=file_id,file_name,data_type' \\\n"
                    "  --data-urlencode 'size=10000' \\\n"
                    "  --data-urlencode 'format=TSV' > files.tsv"
                ),
            ),
        )
    )
    if n_ctrl:
        out.append(
            (
                label,
                AccessStep(
                    order=0,
                    action="Pass the token when the agent needs controlled files",
                    detail=(
                        "Without a token the same endpoints return the open subset and "
                        "HTTP 200. An agent that treats a short result as the whole "
                        "cohort will silently under-count; filter on access and compare "
                        "against the counts on this page."
                    ),
                    url=GDC_API,
                    audience=AccessAudience.AGENT,
                    requires=["GDC authentication token"],
                    cli_snippet=(
                        'curl -H "X-Auth-Token: $GDC_TOKEN" \\\n'
                        "  'https://api.gdc.cancer.gov/data/<file_id>' -o file.bam"
                    ),
                ),
            )
        )
    return out


def _pdc(rec: DatasetRecord) -> list[tuple[str, AccessStep]]:
    studies = _ids(rec, "pdc_study_id")
    study = _first(studies)
    if not study:
        return []
    label = "PDC data use guidelines"
    spans = (
        f" This cohort spans {len(studies)} PDC studies ({', '.join(studies)}); repeat for each."
        if len(studies) > 1
        else ""
    )
    return [
        (
            label,
            AccessStep(
                order=0,
                action="Open the study in the PDC portal",
                detail=(
                    "Proteomic data are released open: no account, no request, no waiting." + spans
                ),
                url=rec.landing_page_url,
                est_time="5 minutes",
            ),
        ),
        (
            label,
            AccessStep(
                order=0,
                action="Accept the data use guidelines and download",
                detail=(
                    "The portal asks you to accept the guidelines at download time. "
                    "They ask for citation and acknowledgement, not for approval."
                ),
                url=PDC_TERMS,
                est_time="minutes to hours, by study size",
            ),
        ),
        (
            label,
            AccessStep(
                order=0,
                action="Resolve the study UUID, then fetch the file manifest",
                detail=(
                    f"filesPerStudy keys on the version UUID, not on {study}. Passing "
                    "the PDC study id returns one row per file with every field null - "
                    "a successful call that looks like a study whose files carry no "
                    "metadata. Resolve the latest version through studyCatalog first. "
                    "acceptDUA: true is the programmatic form of the portal's terms "
                    "click; without it there are no signed download URLs."
                ),
                url=PDC_API,
                audience=AccessAudience.AGENT,
                cli_snippet=(
                    "python3 - <<'PY'\n"
                    "import requests\n"
                    f'STUDY = "{study}"\n'
                    'GQL = "https://pdc.cancer.gov/graphql"\n'
                    'catalog = requests.post(GQL, json={"query": "{ studyCatalog'
                    "(acceptDUA: true) { pdc_study_id versions { study_id "
                    'is_latest_version } } }"}).json()["data"]["studyCatalog"]\n'
                    'uuid = next(v["study_id"] for s in catalog '
                    'if s["pdc_study_id"] == STUDY\n'
                    '            for v in s["versions"] '
                    'if v["is_latest_version"] == "yes")\n'
                    'q = \'{ filesPerStudy(study_id: "%s" acceptDUA: true) '
                    "{ file_id file_name file_type data_category } }' % uuid\n"
                    'files = requests.post(GQL, json={"query": q})'
                    '.json()["data"]["filesPerStudy"]\n'
                    'print(len(files), "files")\n'
                    "PY"
                ),
            ),
        ),
    ]


def _idc(rec: DatasetRecord) -> list[tuple[str, AccessStep]]:
    coll = _first(_ids(rec, "idc_collection_id"))
    if not coll:
        return []
    label = "IDC and TCIA data usage policy"
    return [
        (
            label,
            AccessStep(
                order=0,
                action="Open the collection in the IDC portal",
                detail=(
                    "Imaging is public and stays in DICOM. Browse the series before "
                    "downloading; collections run to terabytes."
                ),
                url=rec.landing_page_url,
                est_time="5 minutes",
            ),
        ),
        (
            label,
            AccessStep(
                order=0,
                action="Read the collection's own licence",
                detail=(
                    (rec.access.license or "Per-collection licence")
                    + ". IDC licences differ by collection, and a non-commercial clause "
                    "on one collection does not travel to the next."
                ),
                url=TCIA_POLICY,
                est_time="5 minutes",
            ),
        ),
        (
            label,
            AccessStep(
                order=0,
                action="Download with idc-index",
                detail=(
                    "The package resolves the collection to its buckets and pulls them "
                    "with s5cmd. No account, no cloud project."
                ),
                url=IDC_INDEX,
                est_time="hours for a full collection",
                cli_snippet=(
                    "pip install idc-index\n"
                    'python -c "from idc_index import IDCClient; '
                    f"IDCClient().download_from_selection(collection_id='{coll}', "
                    "downloadDir='.')\""
                ),
            ),
        ),
        (
            label,
            AccessStep(
                order=0,
                action="List the series before pulling any pixels",
                detail=(
                    "One row per DICOM series, with modality and size, so an agent can "
                    "decide what to fetch instead of fetching everything."
                ),
                url=IDC_DOCS,
                audience=AccessAudience.AGENT,
                cli_snippet=(
                    'python -c "from idc_index import IDCClient; '
                    f"df = IDCClient().get_series(collection_id='{coll}'); "
                    "print(len(df), df['Modality'].value_counts().to_dict())\""
                ),
            ),
        ),
    ]


