BUILDERS = {
    "GDC": _gdc,
    "PDC": _pdc,
    "IDC": _idc,
    "cBioPortal": _cbioportal,
    "HTAN": _htan,
}


def derive(rec: DatasetRecord) -> list[AccessStep]:
    """The route for one record, human steps first, numbered from one."""
    short = rec.repository.short_name if rec.repository else None
    builder = BUILDERS.get(short or "")
    if builder is None:
        return []
    built = builder(rec)
    human = [(lbl, s) for lbl, s in built if s.audience == AccessAudience.HUMAN]
    agent = [(lbl, s) for lbl, s in built if s.audience == AccessAudience.AGENT]
    out: list[AccessStep] = []
    for i, (lbl, step) in enumerate(human + agent, start=1):
        step.order = i
        step.evidence = [_evidence(step.url or "", lbl)] if step.url else [_evidence("", lbl)]
        out.append(step)
    return out


def apply_all(records: list[DatasetRecord]) -> dict[str, int]:
    """Fill in a route wherever no reviewer wrote one.

    A reviewed route is kept whole. Reviewers wrote those routes for a person, though, so
    where one carries nothing for an agent the derived machine steps are appended after
    it: the reviewer's judgement about the human route is not evidence that no API exists.
    """
    stats = {
        "n_derived": 0,
        "n_kept_curated": 0,
        "n_curated_given_machine_steps": 0,
        "n_no_builder": 0,
        "n_steps": 0,
    }
    for rec in records:
        curated = [s for s in rec.access_steps if not is_derived(s)]
        if curated:
            stats["n_kept_curated"] += 1
            if not any(s.audience == AccessAudience.AGENT for s in curated):
                machine = [s for s in derive(rec) if s.audience == AccessAudience.AGENT]
                for i, step in enumerate(machine, start=len(curated) + 1):
                    step.order = i
                rec.access_steps = curated + machine
                if machine:
                    stats["n_curated_given_machine_steps"] += 1
                    stats["n_steps"] += len(machine)
            else:
                rec.access_steps = curated
            continue
        steps = derive(rec)
        if not steps:
            stats["n_no_builder"] += 1
            continue
        rec.access_steps = steps
        stats["n_derived"] += 1
        stats["n_steps"] += len(steps)
    return stats
