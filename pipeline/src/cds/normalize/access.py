"""The route from a dataset page to the data, for a person and for an agent.

Twenty datasets have a route because a reviewer wrote one. Every other record carried a
single sentence naming the kind of door - "direct download, no account required",
"controlled through dbGaP" - which tells a reader what they are up against and not one
thing about what to do next. A researcher who has decided a dataset fits should not then
have to go and find out how a repository works.

So the route is derived here from what the repository has already told us: the access
tier, the components it called open or controlled, and the dataset's own identifiers. A
generated route is repository policy applied to one dataset, never an assertion about
that dataset, and it says so: every step carries DERIVED evidence pointing at the policy
page it came from. Reviewer-written routes are left exactly as they are.

Two audiences, because they take different doors to the same files. A person clicks
through a portal and signs an agreement; an agent calls an API, and the thing it most
needs to know is which calls quietly return a subset rather than an error when it has no
credentials.
"""

from __future__ import annotations

from datetime import UTC, datetime

from cds.model import (
    AccessAudience,
    AccessStep,
    Confidence,
    DatasetRecord,
    Evidence,
    Method,
)

# Documentation that states the policy each derived step applies. Checked by `cds verify`
# along with every other link on a page, so a repository reorganising its site shows up
# as a broken link rather than as confident wrong advice.
GDC_TRANSFER_TOOL = "https://gdc.cancer.gov/access-data/gdc-data-transfer-tool"
GDC_CONTROLLED = "https://gdc.cancer.gov/access-data/obtaining-access-controlled-data"
GDC_API = "https://docs.gdc.cancer.gov/API/Users_Guide/Getting_Started/"
PDC_TERMS = "https://pdc.cancer.gov/pdc/data-use-guidelines"
PDC_API = "https://pdc.cancer.gov/data-dictionary/publicapi-documentation/"
IDC_INDEX = "https://github.com/ImagingDataCommons/idc-index"
IDC_DOCS = "https://learn.canceridc.dev/"
TCIA_POLICY = "https://www.cancerimagingarchive.net/data-usage-policies-and-restrictions/"
CBIO_DATASETS = "https://www.cbioportal.org/datasets"
CBIO_DATAHUB = "https://github.com/cBioPortal/datahub"
CBIO_API = "https://docs.cbioportal.org/web-api-and-clients/"
HTAN_ACCESS = "https://humantumoratlas.org/data-access"
SYNAPSE_START = "https://help.synapse.org/docs/Getting-Started.2055471150.html"


def _evidence(url: str, label: str) -> Evidence:
    return Evidence(
        method=Method.DERIVED,
        source_url=url,
        source_label=label,
        retrieved_at=datetime.now(UTC),
        confidence=Confidence.MEDIUM,
        note=(
            "Generated by applying the repository's documented access policy to this "
            "dataset's identifiers. It is not a reviewer's account of this dataset, and "
            "a reviewed route replaces it where one exists."
        ),
    )


def is_derived(step: AccessStep) -> bool:
    """A step this module wrote, rather than one a reviewer wrote."""
    return any(e.method == Method.DERIVED for e in step.evidence)


def _ids(rec: DatasetRecord, scheme: str) -> list[str]:
    seen: list[str] = []
    for ident in rec.identifiers:
        if ident.scheme == scheme and ident.value not in seen:
            seen.append(ident.value)
    return seen


def _first(values: list[str]) -> str | None:
    return values[0] if values else None


def _component(parts: list[str]) -> str | None:
    return parts[0] if parts else None


